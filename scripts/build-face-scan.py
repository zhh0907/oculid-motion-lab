"""Project the licensed reference scan to a height/UV field, offline.

No photographs are edited. Browser geometry samples the original colour map
using these UV coordinates; animated eyelids replace the closed scan lids.
Requires NumPy and SciPy only for regenerating this checked-in data.
"""
from pathlib import Path
import json
import struct
import numpy as np
from scipy.ndimage import distance_transform_edt, gaussian_filter

ROOT = Path(__file__).resolve().parents[1]
b = (ROOT / 'vendor/face/LeePerrySmith.glb').read_bytes()
size = struct.unpack_from('<I', b, 12)[0]
gltf = json.loads(b[20:20 + size])
offset = 20 + size
binary = b[offset + 8:offset + 8 + struct.unpack_from('<I', b, offset)[0]]

def accessor(i):
    a = gltf['accessors'][i]
    v = gltf['bufferViews'][a['bufferView']]
    components = {'VEC3': 3, 'VEC2': 2, 'SCALAR': 1}[a['type']]
    dtype = {5126: '<f4', 5123: '<u2', 5125: '<u4'}[a['componentType']]
    return np.frombuffer(binary, dtype=dtype, offset=v.get('byteOffset', 0) + a.get('byteOffset', 0), count=a['count'] * components).reshape(-1, components)

primitive = gltf['meshes'][0]['primitives'][0]
points = accessor(primitive['attributes']['POSITION']).astype(float)
uv = accessor(primitive['attributes']['TEXCOORD_0'])
triangles = accessor(primitive['indices']).reshape(-1, 3)
# Canthal anchors obtained on a frontal rendering, then ray-cast onto the scan.
# This alignment is for rendering only, not an anatomical measurement claim.
left = np.array([-.71618993, 1.65735567, 1.80253754])
right = np.array([.47733761, 1.66923332, 1.81625419])
scale = .064 / (right[0] - left[0])
centre = (left + right) / 2
points = (points - centre) * scale
points[:, 2] += .008
nx, ny = 241, 361
xmin, xmax, ymin, ymax = -.09, .09, -.14, .13
xx, yy = np.meshgrid(np.linspace(xmin, xmax, nx), np.linspace(ymin, ymax, ny))
height = np.full((ny, nx), -np.inf)
mapped = np.zeros((ny, nx, 2))
for tri in triangles:
    p = points[tri]
    minx, maxx = max(0, int(np.floor((p[:, 0].min() - xmin) / (xmax - xmin) * (nx - 1)))), min(nx - 1, int(np.ceil((p[:, 0].max() - xmin) / (xmax - xmin) * (nx - 1))))
    miny, maxy = max(0, int(np.floor((p[:, 1].min() - ymin) / (ymax - ymin) * (ny - 1)))), min(ny - 1, int(np.ceil((p[:, 1].max() - ymin) / (ymax - ymin) * (ny - 1))))
    if minx > maxx or miny > maxy:
        continue
    sl = np.s_[miny:maxy + 1, minx:maxx + 1]
    x, y = xx[sl], yy[sl]
    det = (p[1, 1] - p[2, 1]) * (p[0, 0] - p[2, 0]) + (p[2, 0] - p[1, 0]) * (p[0, 1] - p[2, 1])
    if abs(det) < 1e-12:
        continue
    a = ((p[1, 1] - p[2, 1]) * (x - p[2, 0]) + (p[2, 0] - p[1, 0]) * (y - p[2, 1])) / det
    c = ((p[2, 1] - p[0, 1]) * (x - p[2, 0]) + (p[0, 0] - p[2, 0]) * (y - p[2, 1])) / det
    d = 1 - a - c
    z = a * p[0, 2] + c * p[1, 2] + d * p[2, 2]
    visible = (a >= -1e-6) & (c >= -1e-6) & (d >= -1e-6) & (z > height[sl])
    height[sl][visible] = z[visible]
    mapped[sl][visible] = (a[..., None] * uv[tri[0]] + c[..., None] * uv[tri[1]] + d[..., None] * uv[tri[2]])[visible]
valid = np.isfinite(height)
nearest = distance_transform_edt(~valid, return_distances=False, return_indices=True)
height = height[tuple(nearest)]
mapped = mapped[tuple(nearest)]
# Submillimetre smoothing removes projected triangle corners while retaining
# the scan's nose, folds and asymmetry. UVs remain from the unmodified map.
height = gaussian_filter(height, .60)
payload = dict(nx=nx, ny=ny, xmin=xmin, xmax=xmax, ymin=ymin, ymax=ymax,
               alignment=dict(scale=scale, centre=centre.tolist()),
               micrometres=np.round(height.ravel() * 1e6).astype(int).tolist(),
               u=np.round(mapped[:, :, 0].ravel() * 65535).astype(int).tolist(),
               v=np.round(mapped[:, :, 1].ravel() * 65535).astype(int).tolist(),
               valid=valid.ravel().astype(int).tolist())
header = '// Derived from Infinite, 3D Head Scan by Lee Perry-Smith (CC BY 3.0).\n// Generated by scripts/build-face-scan.py; see vendor/face/PROVENANCE.json.\n'
(ROOT / 'src/face-reference.mjs').write_text(header + 'export const FACE_REFERENCE=' + json.dumps(payload, separators=(',', ':')) + ';\n', encoding='utf-8', newline='\n')
print(json.dumps({'grid': [nx, ny], 'metresPerSourceUnit': scale, 'sourceCentre': centre.tolist(), 'validPoints': int(valid.sum())}))
